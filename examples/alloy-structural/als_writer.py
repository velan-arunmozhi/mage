"""Deterministic translation of a structural model document plus observed
edges into Alloy source text.

Two checks are generated per run:

- ``NoForbiddenObserved`` evaluates the *same* question the OCL and
  JSON/Mermaid pilots ask: does any one observed edge land on a ``forbidden``
  cell of the authored policy matrix? Every component, external system, and
  observed edge is declared as a Alloy ``one sig``, so the check has exactly
  one instance to consider -- no open exploration, same semantics as the
  siblings' per-edge lookup, just expressed as an Alloy assertion instead of
  a Python predicate or an OCL invariant.
- ``NoTransitiveApiToDatabase`` asks a question the matrix-lookup and OCL
  pilots cannot answer without hand-written graph code: does the authored
  policy, read as a directed graph over *layers*, admit any multi-hop
  permitted path from the ``api`` layer to the ``database`` layer? This uses
  Alloy's transitive-closure operator (``^``) over the ``permitsLayer``
  relation. It is evaluated against the policy alone, independent of any
  observed edge, which is the thing Alloy is actually differentiated for:
  checking a declared relational structure against ALL instances it admits,
  not only the one instance a codebase happened to produce.

Both checks are declared with ``for 0``: every sig here is ``one sig``, so
there is no unscoped population for Alloy to range over and the run is a
single deterministic instance, not a bounded search.
"""
import re

TRANSITIVE_FROM_LAYER = "api"
TRANSITIVE_TO_LAYER = "database"


def _sanitize(prefix: str, raw_id: str) -> str:
    name = re.sub(r"[^A-Za-z0-9_]", "_", raw_id)
    if not name or name[0].isdigit():
        name = "_" + name
    return f"{prefix}_{name}"


def build_als(model: dict, edges: list) -> tuple:
    """Return (als_source, identifier_map).

    ``identifier_map`` records every Alloy identifier minted here, keyed by
    kind, so a counterexample's skolem atom name can be mapped back to a
    model component, external system, layer, relation type, or observed
    edge index without re-deriving the naming scheme at parse time.
    """
    policy = model.get("policy", {})
    layers = sorted(policy.get("layers", []))
    rel_types = sorted(policy.get("relation_types", []))
    components = sorted(model.get("components", []), key=lambda c: c["id"])
    externals = sorted(model.get("external_systems", []), key=lambda e: e["id"])
    matrix = policy.get("matrix", {})

    layer_name = {layer: _sanitize("L", layer) for layer in layers}
    reltype_name = {rt: _sanitize("T", rt) for rt in rel_types}
    comp_name = {c["id"]: _sanitize("C", c["id"]) for c in components}
    ext_name = {e["id"]: _sanitize("X", e["id"]) for e in externals}
    node_name = dict(comp_name)
    node_name.update(ext_name)
    node_layer = {c["id"]: c["layer"] for c in components}
    node_layer.update({e["id"]: e.get("layer") for e in externals if e.get("layer")})

    lines = []
    lines.append("// generated by als_writer.py -- do not hand-edit, regenerate instead")
    lines.append("abstract sig Layer {}")
    if layers:
        lines.append(
            "one sig " + ", ".join(layer_name[l] for l in layers) + " extends Layer {}"
        )
    lines.append("")
    lines.append("abstract sig RelType {}")
    if rel_types:
        lines.append(
            "one sig " + ", ".join(reltype_name[t] for t in rel_types) + " extends RelType {}"
        )
    lines.append("")
    lines.append("abstract sig Node { layer: one Layer }")
    lines.append("sig Component extends Node {}")
    lines.append("sig ExternalSystem extends Node {}")
    lines.append("")
    if comp_name:
        lines.append(
            "one sig " + ", ".join(comp_name[c["id"]] for c in components) + " extends Component {}"
        )
    if ext_name:
        lines.append(
            "one sig " + ", ".join(ext_name[e["id"]] for e in externals) + " extends ExternalSystem {}"
        )
    lines.append("")

    layer_facts = []
    for node_id, layer in sorted(node_layer.items()):
        if layer not in layer_name:
            continue
        layer_facts.append(f"  {node_name[node_id]}.layer = {layer_name[layer]}")
    if layer_facts:
        lines.append("fact NodeLayers {")
        lines.extend(layer_facts)
        lines.append("}")
    lines.append("")

    edge_names = []
    edge_facts = []
    for index, edge in enumerate(edges):
        name = f"E{index}"
        edge_names.append(name)
        edge_facts.append(
            f"  {name}.relType = {reltype_name[edge['type']]} and "
            f"{name}.src = {node_name[edge['from']]} and "
            f"{name}.dst = {node_name[edge['to']]}"
        )
    lines.append("sig Edge { relType: one RelType, src: one Node, dst: one Node }")
    if edge_names:
        lines.append("one sig " + ", ".join(edge_names) + " extends Edge {}")
        lines.append("fact ObservedEdges {")
        lines.extend(edge_facts)
        lines.append("}")
    else:
        lines.append("fact NoEdges { no Edge }")
    lines.append("")

    matrix_clauses = []
    for rel_type, from_map in sorted(matrix.items()):
        for from_layer, to_map in sorted(from_map.items()):
            for to_layer, cell in sorted(to_map.items()):
                if cell == "permitted":
                    matrix_clauses.append(
                        f"  ({reltype_name[rel_type]} = t and "
                        f"{layer_name[from_layer]} = a and {layer_name[to_layer]} = b)"
                    )
    lines.append("pred permitted[t: RelType, a: Layer, b: Layer] {")
    if matrix_clauses:
        lines.append(" or\n".join(matrix_clauses))
    else:
        lines.append("  false")
    lines.append("}")
    lines.append("")

    lines.append("assert NoForbiddenObserved {")
    lines.append("  all e: Edge | permitted[e.relType, e.src.layer, e.dst.layer]")
    lines.append("}")
    lines.append("check NoForbiddenObserved for 0")
    lines.append("")

    # Alloy's transitive-closure operator (^) needs a relation value, not a
    # pred call, so permitsLayer is a parameterless fun returning a binary
    # relation over Layer, derived from the same permitted[] predicate.
    lines.append("fun permitsLayer: Layer -> Layer {")
    lines.append("  { a: Layer, b: Layer | some t: RelType | permitted[t, a, b] }")
    lines.append("}")
    lines.append("assert NoTransitiveApiToDatabase {")
    if TRANSITIVE_FROM_LAYER in layer_name and TRANSITIVE_TO_LAYER in layer_name:
        lines.append(
            f"  {layer_name[TRANSITIVE_TO_LAYER]} not in "
            f"{layer_name[TRANSITIVE_FROM_LAYER]}.^permitsLayer"
        )
    else:
        lines.append("  true")
    lines.append("}")
    lines.append("check NoTransitiveApiToDatabase for 0")
    lines.append("")

    identifier_map = {
        "layers": {v: k for k, v in layer_name.items()},
        "rel_types": {v: k for k, v in reltype_name.items()},
        "nodes": {v: k for k, v in node_name.items()},
        "edges": {name: edges[i] for i, name in enumerate(edge_names)},
    }
    return "\n".join(lines) + "\n", identifier_map
